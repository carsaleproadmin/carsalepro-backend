const REPORT_CODE_PATTERN =
  /^CSP-(\d{1,12}|[0-9a-f]{8}-[0-9a-f]{4}-4[0-9a-f]{3}-[89ab][0-9a-f]{3}-[0-9a-f]{12})$/i;

/**
 * Trim only — NEVER upper-case.
 *
 * The mobile app mints `CSP-` + a LOWER-CASE uuid v4
 * (`carsalepro-mobile/lib/core/utils/report_code.dart`) and `Report.code` is
 * matched literally in Postgres, so upper-casing here turned every genuine
 * modern Report ID into a 404 on the attach path — the same code answered 200
 * from the public preview endpoint and 404 here. `REPORT_CODE_PATTERN` already
 * carries the `/i` flag, so validation is unaffected.
 *
 * `src/public/dto/report-lookup.dto.ts` (trim) and
 * `src/listings/dto/create-listing.dto.ts` (no transform at all) were already
 * correct; this DTO was the outlier.
 */
const normalizeReportCode = ({ value }: { value: unknown }) =>
  typeof value === 'string' ? value.trim() : value;

export class AttachOrderReportDto {
  @ApiProperty({
    example: 'CSP-67e5a3d2-9c41-4b7e-8f2a-1d3c5e7a9b0f',
    description: 'Report code generated by the mobile inspection app.',
  })
  @Transform(normalizeReportCode)
  @IsString()
  @MaxLength(48)
  @Matches(REPORT_CODE_PATTERN, { message: 'code must be a CSP report code' })
  code!: string;
}

export class DisputeOrderDto {
  @ApiProperty({ example: 'Inspector never showed up' })
  @IsString()
  @MaxLength(1000)
  reason!: string;
}

/**
 * The reason an inspector must give to hand an accepted order back.
 *
 * The reason is NOT optional and NOT allowed to be blank: the customer reads it
 * in the cancellation letter, and "the inspector cancelled, no reason given" is
 * the answer that makes them call support. `Transform` trims first, so a body of
 * spaces fails `Length` instead of passing as text.
 */
export class DeclineOrderDto {
  @ApiProperty({ example: 'My van broke down and I cannot reach the address today' })
  @IsString()
  @Transform(({ value }) => (typeof value === 'string' ? value.trim() : value))
  @Length(3, 1000)
  reason!: string;
}

