import { ApiProperty, ApiPropertyOptional } from '@nestjs/swagger';
import {
  IsBoolean,
  IsEnum,
  IsISO8601,
  IsLatitude,
  IsLongitude,
  IsNotEmpty,
  IsOptional,
  IsString,
  Length,
  Matches,
  MaxLength,
} from 'class-validator';
import { Transform } from 'class-transformer';

export class QuoteOrderDto {
  @ApiProperty({ example: 52.52 })
  @IsLatitude()
  lat!: number;

  @ApiProperty({ example: 13.405 })
  @IsLongitude()
  lng!: number;

  /**
   * DEPRECATED (DEN-290). The customer no longer chooses a time, and the price
   * does not depend on one. Accepted only so a website deployed before that
   * change does not get a 400. Do not send it from new code.
   */
  @ApiPropertyOptional({ example: '2026-07-01T09:00:00.000Z', deprecated: true })
  @IsOptional()
  @IsISO8601()
  scheduledAt?: string;
}

export class CreateOrderDto {
  @ApiPropertyOptional({ example: '1HGBH41JXMN109186', minLength: 17, maxLength: 17 })
  @IsOptional()
  @IsString()
  @Length(17, 17)
  @Matches(/^[A-HJ-NPR-Z0-9]{17}$/i)
  vin?: string;

  @ApiProperty({ example: 'BMW' })
  @IsString()
  @MaxLength(64)
  make!: string;

  @ApiProperty({ example: '320d' })
  @IsString()
  @MaxLength(64)
  model!: string;

  /**
   * The seller's phone number OR a link to the listing, as free text (DEN-116).
   * Required since DEN-291: the assigned inspector must contact the car owner
   * before the trip, and this is the only channel the order carries. The name
   * stayed `listingUrl` so the wire contract did not change.
   */
  @ApiProperty({ example: '+4930123456 or https://mobile.de/listing/123' })
  @Transform(({ value }) => (typeof value === 'string' ? value.trim() : value))
  @IsString()
  @IsNotEmpty()
  @MaxLength(2048)
  listingUrl!: string;

  @ApiProperty({ example: 'Musterstraße 1, 10115 Berlin' })
  @IsString()
  @MaxLength(240)
  address!: string;

  @ApiProperty({ example: 52.52 })
  @IsLatitude()
  lat!: number;

  @ApiProperty({ example: 13.405 })
  @IsLongitude()
  lng!: number;

  /**
   * DEPRECATED (DEN-290). The customer no longer chooses a time, and the price
   * does not depend on one. Accepted only so a website deployed before that
   * change does not get a 400. Do not send it from new code.
   */
  @ApiPropertyOptional({ example: '2026-07-01T09:00:00.000Z', deprecated: true })
  @IsOptional()
  @IsISO8601()
  scheduledAt?: string;
}

